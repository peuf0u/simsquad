// installedTestSkill installs the skills into a temp repo and returns the
// simsquad-test skill's SKILL.md and worker.md as an agent would read them.
func installedTestSkill(t *testing.T) (skill, worker string) {
	t.Helper()
	root := t.TempDir()
	if _, err := skills.Install(skills.Options{Root: root, Version: "0.4.0"}); err != nil {
		t.Fatal(err)
	}
	dir := filepath.Join(root, skills.DefaultDir, "simsquad-test")
	read := func(name string) string {
		b, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			t.Fatal(err)
		}
		return string(b)
	}
	return read("SKILL.md"), read("worker.md")
}

// fencedCommands returns the command lines inside fenced code blocks that
// start with prog, with backslash continuations joined into one line.
func fencedCommands(doc, prog string) []string {
	var out []string
	inFence := false
	pending := ""
	for _, line := range strings.Split(doc, "\n") {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "```") {
			inFence = !inFence
			pending = ""
			continue
		}
		if !inFence {
			continue
		}
		if pending != "" {
			trimmed = pending + " " + trimmed
			pending = ""
		}
		if strings.HasSuffix(trimmed, `\`) {
			pending = strings.TrimSuffix(trimmed, `\`)
			continue
		}
		if strings.HasPrefix(trimmed, prog+" ") {
			out = append(out, trimmed)
		}
	}
	return out
}

