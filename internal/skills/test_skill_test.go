// The result.json example in the worker prompt is what workers copy, so it
// must pass `run validate` once its screenshots exist.
func TestWorkerResultExamplePassesValidation(t *testing.T) {
	_, worker := installedTestSkill(t)
	m := regexp.MustCompile("(?s)## result.json\n\n```json\n(.*?)```").FindStringSubmatch(worker)
	if m == nil {
		t.Fatal("worker prompt has no result.json example")
	}
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, contract.ResultFileName), []byte(m[1]), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Join(dir, "screenshots"), 0o755); err != nil {
		t.Fatal(err)
	}
	for _, shot := range regexp.MustCompile(`screenshots/[a-z0-9-]+\.png`).FindAllString(m[1], -1) {
		if err := os.WriteFile(filepath.Join(dir, shot), []byte("png"), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	if _, errs := agenttest.ValidateWorkerDir(dir); len(errs) > 0 {
		t.Errorf("example result.json is invalid: %v", errs)
	}
}
