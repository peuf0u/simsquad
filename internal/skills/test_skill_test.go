// Every simsquad command and flag the skill or the worker prompt shows must
// exist on the binary, so neither teaches a command simsquad rejects.
func TestTestSkillUsesOnlyRealSimsquadCommandsAndFlags(t *testing.T) {
	skill, worker := installedTestSkill(t)
	flagRe := regexp.MustCompile(`(?:^|\s)--([a-z][a-z-]*)`)
	for _, line := range append(fencedCommands(skill, "simsquad"), fencedCommands(worker, "simsquad")...) {
		// Flags after `--` belong to the wrapped worker command.
		own, _, _ := strings.Cut(line, " -- ")
		fields := strings.Fields(own)[1:]
		var words []string
		for _, f := range fields {
			if strings.HasPrefix(f, "-") {
				break
			}
			words = append(words, f)
		}
		root := cli.NewRootCmd()
		cmd, rest, err := root.Find(words)
		if err != nil || cmd == root || cmd.HasSubCommands() {
			t.Errorf("unknown command in: %s", line)
			continue
		}
		// `run worker` validates its arguments against the `--` split, which
		// only a real parse sets up; every other command is checked here.
		if cmd.Args != nil && !strings.Contains(line, " -- ") {
			if err := cmd.Args(cmd, rest); err != nil {
				t.Errorf("`%s` rejects its arguments %v: %s", cmd.CommandPath(), rest, line)
			}
		}
		for _, f := range flagRe.FindAllStringSubmatch(own, -1) {
			if cmd.Flags().Lookup(f[1]) == nil && cmd.InheritedFlags().Lookup(f[1]) == nil {
				t.Errorf("`%s` has no --%s flag: %s", cmd.CommandPath(), f[1], line)
			}
		}
	}
}

// mobilecliCommands is the mobilecli 1.0.13 surface workers may use, with
// each command's flags, as printed by `mobilecli <command> --help`.
var mobilecliCommands = map[string][]string{
	"dump ui":      {"device", "format", "full"},
	"io tap":       {"device"},
	"io longpress": {"device"},
	"io text":      {"device"},
	"io swipe":     {"device", "duration"},
	"io button":    {"device"},
	"screenshot":   {"device", "output", "format", "quality", "scale", "max-size"},
	"apps launch":  {"device", "activity", "locale"},
}

func TestWorkerDrivesItsOwnDeviceWithRealMobilecliCommands(t *testing.T) {
	_, worker := installedTestSkill(t)
	cmds := fencedCommands(worker, "mobilecli")
	if len(cmds) == 0 {
		t.Fatal("worker prompt has no mobilecli examples")
	}
	seen := map[string]bool{}
	flagRe := regexp.MustCompile(`(?:^|\s)--([a-z][a-z-]*)`)
	for _, line := range cmds {
		fields := strings.Fields(line)
		name := ""
		for k := range mobilecliCommands {
			if strings.HasPrefix(strings.Join(fields[1:], " ")+" ", k+" ") {
				name = k
			}
		}
		if name == "" {
			t.Errorf("not a mobilecli command workers may use: %s", line)
			continue
		}
		seen[name] = true
		if !strings.Contains(line, "--device ") {
			t.Errorf("mobilecli call does not target the worker's own device: %s", line)
		}
		for _, f := range flagRe.FindAllStringSubmatch(line, -1) {
			ok := false
			for _, allowed := range mobilecliCommands[name] {
				ok = ok || allowed == f[1]
			}
			if !ok {
				t.Errorf("`mobilecli %s` has no --%s flag: %s", name, f[1], line)
			}
		}
	}
	for _, want := range []string{"dump ui", "io tap", "io text", "io swipe", "io button", "screenshot", "apps launch"} {
		if !seen[want] {
			t.Errorf("worker prompt shows no `mobilecli %s` example", want)
		}
	}
	if !strings.Contains(worker, "--format text") {
		t.Error("worker prompt does not read the screen with `dump ui --format text`")
	}
}

